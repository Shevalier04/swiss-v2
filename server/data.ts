export interface Course {
  id: number;
  name: string;
  teacher?: string;
  room?: string;
  day: number; // 0=Monday, 6=Sunday
  s: number;   // start slot 1-11
  e: number;   // end slot 1-11
  weeks?: string; // e.g. "2-14周,16-17周"
  color: string;
}

export interface Homework {
  id: number;
  course: string;
  title: string;
  due?: string; // "YYYY-MM-DD" or "YYYY-MM-DD HH:mm"
  done: boolean;
  source?: string;
  type?: '作业' | '考试';
  submitStatus?: string;
  remainingTime?: string;
  detailPath?: string;
}

export interface TaskItem {
  id: number;
  title: string;
  done: boolean;
}

export interface UserAccount {
  username: string;
  name: string;
  pwHash: string;
  role: 'admin' | 'user';
  created: number;
  disabled: boolean;
}

export interface Notice {
  id: number;
  text: string;
  by: string;
  time: number;
}

